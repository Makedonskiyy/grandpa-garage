#!/usr/bin/env node
/**
 * build-sound-doc — таблица звуков для звукорежиссёров (docs/sound/README.md)
 * из каталога data/sounds.json. Требования к файлам и лицензиям — в шапке ниже.
 *   npm run sound-doc
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const c = JSON.parse(readFileSync(`${ROOT}data/sounds.json`, 'utf8'));
const has = (s) => existsSync(`${ROOT}src/assets/audio/${s.group}/${s.key}.mp3`);
const rows = c.sounds
  .map(
    (s) =>
      `| \`${s.group}/${s.key}.mp3\` | ${c.groups[s.group]} | ${s.duration} с | ${s.loop ? 'да' : 'нет'} | ${s.what} | ${has(s) ? 'есть' : '—'} |`,
  )
  .join('\n');

const md = `# Звук «Дедова гаража» — задание для звукорежиссёров

Все звуки кладутся в [\`src/assets/audio/\`](../../src/assets/audio) — по папкам групп, имя файла = ключ из таблицы. Игра подхватывает файлы сама при сборке: недостающие просто молчат, в коде ничего менять не нужно. Громкость каждого звука в игре — поле \`volume\` в [\`data/sounds.json\`](../../data/sounds.json). Таблица пересобирается командой \`npm run sound-doc\` (колонка «Готов» — есть ли файл).

## Формат — один: MP3

- **MP3, 44,1 кГц.** Играет во всех браузерах (Chrome, Яндекс, Firefox, Safari и iPhone), маленький размер для сайта.
- **Музыка и атмосфера** — стерео, 160–192 кбит/с. **Короткие звуки** — моно или стерео, 128 кбит/с.
- **Исходники (WAV 48 кГц / 24 бит) храните у себя**, в репозиторий — только готовые MP3.
- **Петли** (колонка «Петля»): бесшовные — конец переходит в начало без щелчка и без затухания, резать по нулю. У MP3 бывает микропауза на стыке, поэтому в начале и конце петли не должно быть тишины; петлю мотора делайте не короче 1 с.
- **Короткие звуки** начинаются сразу (тишины в начале не больше 10 мс), хвост — естественный, без обрезки.
- **Громкость (ориентир):** музыка около −16 LUFS, атмосфера −24 LUFS, звуки — пик не выше −1 dBTP. Финальный баланс — в \`data/sounds.json\`.
- **Мотор** (\`car_engine_loop\`): ровные средние обороты (~3000 об/мин) рядной шестёрки, без перегазовок — игра сама меняет высоту тона от холостых до отсечки.
- **Размер:** трек музыки — до 3 МБ, все звуки вместе — до 15–20 МБ (игра грузит их целиком перед стартом).

## Таблица звуков (${c.sounds.length})

| Файл | Группа | Длительность | Петля | Что звучит | Готов |
| --- | --- | --- | --- | --- | --- |
${rows}

## Лицензии: что можно брать

Игра открытая (GPL-3.0) и лежит публично на GitHub и GitHub Pages — **каждый звук распространяется вместе с игрой**. Поэтому:

- **Нельзя:** треки известных исполнителей, музыку из фильмов, игр, YouTube, ВК, Яндекс Музыки, Spotify; «нашёл в интернете» без лицензии — даже с упоминанием автора. Это нарушение авторских прав, репозиторий и сайт могут заблокировать.
- **Можно без условий:** своё (записали или сочинили сами), **CC0** и public domain.
- **Можно с упоминанием автора:** **CC BY** — имя автора, название, ссылка и лицензия в [CREDITS.md](CREDITS.md) и в титрах. **CC BY-SA** — так же, но изменённый звук тоже выходит под CC BY-SA.
- **Осторожно:** **CC BY-NC** (только некоммерческое) — для джема допустимо, но при продаже игры звук придётся менять. **ND** (без изменений) — нельзя обрезать и обрабатывать.
- **Стоки** (Pixabay, Mixkit и подобные): разрешают звук в игре, но не выкладывать его отдельно — нам подходит; ссылку на условия сохраните в CREDITS.md.
- **Нейросети** (Suno, Udio и т. п.): права зависят от тарифа, на бесплатном коммерческое использование обычно запрещено. Проверяйте условия и сохраняйте ссылку.

**Где брать (открываются из России):** freesound.org (фильтр по лицензии CC0 / CC BY), opengameart.org, pixabay.com/sound-effects, бесплатные бандлы Sonniss GameAudioGDC (роялти-фри), jsfxr — для «игровых» писков и щелчков (результат ваш).

**Для каждого чужого звука** — строка в [CREDITS.md](CREDITS.md): файл, автор, название, ссылка, лицензия, что изменено.

## Что ещё важно

- **Звук включается только после первого клика** — так требуют браузеры; заставка уже просит нажать.
- **Настройки:** ползунок «Музыка» — для музыки, «Звуки» — для атмосферы и всех звуков, плюс «Без звука».
- **Частые звуки** (печать текста, наведение, педали) — тихие и очень короткие, иначе надоедают.
- **Реплики не озвучены:** музыка под сценами тихая и без вокала, чтобы не спорить с текстом.
- **Без клиппинга:** в браузере нет лимитера, громкие звуки складываются друг с другом.
- **Единый характер:** 2004 год, гаражи, тёплый «ламповый» звук — без космических синтов и мобильных звенелок.
`;

mkdirSync(`${ROOT}docs/sound`, { recursive: true });
writeFileSync(`${ROOT}docs/sound/README.md`, md);
const credits = `${ROOT}docs/sound/CREDITS.md`;
if (!existsSync(credits)) {
  writeFileSync(
    credits,
    '# Авторы звуков\n\nКаждый звук, сделанный не нами.\n\n| Файл | Автор | Название | Ссылка | Лицензия | Изменения |\n| --- | --- | --- | --- | --- | --- |\n',
  );
}
console.log(`✓ docs/sound/README.md: ${c.sounds.length} звуков`);
